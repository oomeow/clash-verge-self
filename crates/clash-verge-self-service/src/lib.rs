#[cfg(windows)]
use windows_service::service::ServiceType;

use crate::service::SecureChannel;

#[cfg(windows)]
pub const SERVICE_TYPE: ServiceType = ServiceType::OWN_PROCESS;
pub const SERVICE_NAME: &str = "clash_verge_self_service";

// default server id
pub const DEFAULT_SERVER_ID: &str = "verge-self-service-server";

/// File name of the per-install pre-shared key, stored in the app data dir.
///
/// The key is generated by the elevated installer and is readable only by the
/// installing user (and root/SYSTEM), so it is never shipped inside the app or
/// service binaries.
pub const PSK_FILE_NAME: &str = "service.psk";

/// Length in bytes of the pre-shared key.
pub const PSK_LEN: usize = 32;

/// Core slot names the service is allowed to launch.
///
/// The service never trusts a caller-supplied executable path: it resolves the
/// core binary from one of these names inside the app directory pinned at
/// install time, so a compromised client cannot make it run an arbitrary
/// program as root.
pub const ALLOWED_CORES: [&str; 2] = ["self-mihomo", "self-mihomo-alpha"];

// encode relate
const KEY_INFO: &[u8] = b"7f3b9d2c8a1e4f6b9d0a5c2e1f8b3d7a";

/// Generate a fresh random pre-shared key.
pub fn generate_psk() -> [u8; PSK_LEN] {
    use chacha20poly1305::aead::{OsRng, rand_core::RngCore};

    let mut psk = [0u8; PSK_LEN];
    OsRng.fill_bytes(&mut psk);
    psk
}

/// Read and validate a pre-shared key from `path`.
pub fn read_psk(path: &Path) -> Result<[u8; PSK_LEN]> {
    let bytes = std::fs::read(path)
        .map_err(|e| ServiceError::General(format!("failed to read service key {}: {e}", path.display())))?;
    if bytes.len() != PSK_LEN {
        return Err(ServiceError::General(format!(
            "invalid service key length: expected {PSK_LEN}, got {}",
            bytes.len()
        )));
    }
    let mut psk = [0u8; PSK_LEN];
    psk.copy_from_slice(&bytes);
    Ok(psk)
}

/// Derive the pre-shared key path from the app data dir (the parent of the logs dir).
pub fn psk_path_from_data_dir(data_dir: &Path) -> PathBuf {
    data_dir.join(PSK_FILE_NAME)
}

pub struct Client(SecureChannel);

impl Client {
    /// connect to server
    ///
    /// unix system: `/tmp/{server_id}.sock`
    ///
    /// Windows system: `\\.\pipe\{server_id}`
    pub async fn connect<S: Into<String>>(server_id: S, psk: &[u8]) -> Result<Self> {
        let temp_dir = if cfg!(windows) {
            std::env::temp_dir()
        } else {
            PathBuf::from("/tmp")
        };
        let path = ServerId::new(server_id.into()).parent_folder(temp_dir);
        let client = tipsy::Endpoint::connect(path).await?;
        let secured = SecureChannel::handshake_client(client, psk).await?;
        Ok(Self(secured))
    }

    /// send socket command request
    pub async fn send<T: DeserializeOwned>(&mut self, command: model::SocketCommand) -> Result<model::JsonResponse<T>> {
        let cmd_json = serde_json::to_string(&command)?;
        self.0.send(cmd_json.as_bytes()).await?;
        let res = self.0.recv().await?;
        let msg = String::from_utf8(res)?;
        let res = model::JsonResponse::from_str(&msg)?;
        Ok(res)
    }
}

pub struct Server;

impl Server {
    /// run server
    ///
    /// `core_dir` is the directory holding the app executable and its bundled
    /// core sidecars (Tauri `externalBin`); it is the only place the service
    /// will launch a core from.
    pub async fn run<S: Into<String>>(server_id: S, psk: &[u8], core_dir: &Path) -> Result<()> {
        service::run_service(Some(server_id.into()), psk, core_dir).await?;
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generate_psk_is_random_and_sized() {
        let a = generate_psk();
        let b = generate_psk();
        assert_eq!(a.len(), PSK_LEN);
        assert_ne!(a, b, "two generated keys must not be equal");
    }

    #[test]
    fn read_psk_roundtrips_a_valid_key() {
        let dir = std::env::temp_dir().join(format!("cvs-psk-test-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let path = psk_path_from_data_dir(&dir);
        let psk = generate_psk();
        std::fs::write(&path, psk).unwrap();

        assert_eq!(read_psk(&path).unwrap(), psk);

        std::fs::remove_file(&path).unwrap();
        std::fs::remove_dir_all(&dir).unwrap();
    }

    #[test]
    fn read_psk_rejects_wrong_length() {
        let dir = std::env::temp_dir().join(format!("cvs-psk-bad-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let path = psk_path_from_data_dir(&dir);
        std::fs::write(&path, b"too-short").unwrap();

        assert!(read_psk(&path).is_err());

        std::fs::remove_file(&path).unwrap();
        std::fs::remove_dir_all(&dir).unwrap();
    }

    #[test]
    fn psk_path_from_data_dir_appends_file_name() {
        let path = psk_path_from_data_dir(Path::new("/tmp/app-home"));
        assert_eq!(path, Path::new("/tmp/app-home").join(PSK_FILE_NAME));
    }
}
